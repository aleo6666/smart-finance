async def seed_public_knowledge(
    db: AsyncSession,
    client: AsyncQdrantClient,
    settings: Settings,
    *,
    embedder: Embedder = embed_text,
) -> dict[str, int]:
    titles = [document["title"] for document in PUBLIC_KNOWLEDGE_DOCUMENTS]
    existing = set(
        (
            await db.scalars(
                select(KnowledgeDocument.title).where(
                    KnowledgeDocument.space_id == 0,
                    KnowledgeDocument.title.in_(titles),
                )
            )
        ).all()
    )
    created = 0
    for seed in PUBLIC_KNOWLEDGE_DOCUMENTS:
        if seed["title"] in existing:
            continue
        await ingest_knowledge_document(
            db,
            client,
            settings,
            user_id=0,
            space_id=0,
            title=seed["title"],
            source_type="seed",
            file_path=None,
            text=seed["content"],
            embedder=embedder,
        )
        created += 1
    total = len(PUBLIC_KNOWLEDGE_DOCUMENTS)
    return {"created": created, "skipped": total - created, "total": total}
